/* ---------- prebuilt React components ---------- */

// packages/react is built before the docs site starts (predev / prebuild), so its dist is bundled here as text.
// Components are the same for everyone; only the tokens differ per export.
const componentFiles = import.meta.glob('../../../../packages/react/dist/**/*', {
  query: '?raw',
  import: 'default',
  eager: true,
}) as Record<string, string>;

/** dist/index.js -> components/index.js, dist/types/X.d.ts -> components/X.d.ts, dist/components.css -> components.css */
function componentEntries(dir: string): ZipEntry[] {
  const entries = Object.entries(componentFiles).map(([path, content]) => {
    const rel = path.split('/dist/')[1];
    const target = rel === 'components.css' ? rel : `components/${rel.replace(/^types\//, '')}`;
    return { path: `${dir}/${target}`, content };
  });
  if (!entries.some((e) => e.path.endsWith('components/index.js'))) {
    throw new Error('Component build missing: run "npm run build -w @design-token/react" and restart the site');
  }
  return entries;
}

/** Everything needed to `npm publish`, inside a folder named after the package */
export function buildNpmPackage(themes: Themes, options: PackageOptions): ZipEntry[] {
  const json = buildJson(themes, options);
  const data = JSON.parse(json);
  const dir = packageSlug(options.name);
  return [
    { path: `${dir}/package.json`, content: buildPackageJson(options) },
    { path: `${dir}/tokens.json`, content: json },
    { path: `${dir}/tokens.css`, content: buildCss(themes) },
    { path: `${dir}/index.js`, content: buildIndexJs(json) },
    { path: `${dir}/index.cjs`, content: buildIndexCjs(json) },
    { path: `${dir}/index.d.ts`, content: buildIndexDts(data) },
    ...componentEntries(dir),
    { path: `${dir}/README.md`, content: buildReadme(options) },
  ];
}
