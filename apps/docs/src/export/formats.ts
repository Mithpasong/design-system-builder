const cssReadme = () => `# Design tokens (HTML / CSS)

Generated by Design System Builder on ${stamp()}.

- tokens.css: every token as a CSS custom property (--dt-*), light by default, dark via
  <html data-theme="dark"> or the OS dark preference.
- index.html: token preview page (colors, type, spacing, shadow).
- components.css: every component (dt-button, dt-card, ...). Needs tokens.css.
- components.html: all components as static HTML in the docs layout, including open
  dialogs, drawers, menus and popovers. Open it in a browser next to the CSS files.

The markup is static: copy the HTML of a component and keep its dt-* classes.
Behavior (opening menus, switching tabs, toasts) comes from the React package.

## Use

<link rel="stylesheet" href="tokens.css" />

.button {
  height: var(--dt-size-md-height);
  padding: 0 var(--dt-size-md-padding-x);
  border-radius: var(--dt-radius-md);
  background: var(--dt-primary);
  color: var(--dt-primary-foreground);
}
`;

export function buildCssZip(themes: Themes): ZipEntry[] {
  return [
    { path: 'tokens.css', content: buildCss(themes) },
    { path: 'index.html', content: buildPreviewHtml(themes) },
    { path: 'README.md', content: cssReadme() },
  ];
}
