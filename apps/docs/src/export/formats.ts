const kebab = (key: string) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const stamp = () => `${new Date().toISOString().slice(0, 19).replace('T', ' ')} UTC`;

/* ---------- Figma: DTCG token files, one per mode ---------- */

// Figma's DTCG import maps color, dimension (px), duration (s) and number tokens to variables.
// Shadows and easing curves have no variable type, so shadows are split into numbers and easing is omitted.

function dtcgColor(hex: string) {
  const n = parseInt(hex.slice(1), 16);
  const components = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => Math.round((v / 255) * 10000) / 10000);
  return { $type: 'color', $value: { colorSpace: 'srgb', components, alpha: 1, hex: hex.toLowerCase() } };
}
const dtcgPx = (value: number) => ({ $type: 'dimension', $value: { value, unit: 'px' } });
const dtcgNumber = (value: number) => ({ $type: 'number', $value: value });
const dtcgDuration = (ms: number) => ({ $type: 'duration', $value: { value: ms / 1000, unit: 's' } });

function toDtcg(theme: Theme) {
  const accents = (group: Record<string, string>) =>
    Object.fromEntries(
      Object.entries(group).flatMap(([name, hex]) => [
        [name, dtcgColor(hex)],
        [`${name}-foreground`, dtcgColor(getForeground(hex))],
      ]),
    );
  const scale = getTypeScale(theme.typography);

  return {
    color: {
      brand: accents(theme.brand),
      status: accents(theme.status),
      neutral: Object.fromEntries(Object.entries(theme.neutral).map(([k, v]) => [kebab(k), dtcgColor(v)])),
      'focus-ring': dtcgColor(theme.focusRing.color),
      shadow: dtcgColor(theme.shadow.color),
    },
    font: {
      size: Object.fromEntries(scale.map((s) => [s.name, dtcgPx(s.fontSize)])),
      'line-height': Object.fromEntries(scale.map((s) => [s.name, dtcgPx(s.lineHeight)])),
      weight: Object.fromEntries(Object.entries(theme.typography.weights).map(([k, v]) => [k, dtcgNumber(v)])),
    },
    size: Object.fromEntries(
      Object.entries(theme.size).map(([k, v]) => [k, { height: dtcgPx(v.height), 'padding-x': dtcgPx(v.paddingX) }]),
    ),
    space: Object.fromEntries(getSpacingScale(theme.spacing).map((s) => [s.name, dtcgPx(s.value)])),
    radius: {
      ...Object.fromEntries(Object.entries(theme.radius).map(([k, v]) => [k, dtcgPx(v)])),
      full: dtcgPx(9999),
    },
    'border-width': Object.fromEntries(Object.entries(theme.border).map(([k, v]) => [k, dtcgPx(v)])),
    shadow: {
      opacity: dtcgNumber(theme.shadow.opacity),
      ...Object.fromEntries(
        shadowLevels.map((l) => [l, { y: dtcgPx(theme.shadow.levels[l].y), blur: dtcgPx(theme.shadow.levels[l].blur) }]),
      ),
    },
    duration: Object.fromEntries(Object.entries(theme.motion.duration).map(([k, v]) => [k, dtcgDuration(v)])),
    'focus-ring': { width: dtcgPx(theme.focusRing.width), offset: dtcgPx(theme.focusRing.offset) },
  };
}

/* ---------- Figma plugin: variables + styles + components ---------- */

interface PluginVariable {
  name: string;
  type: 'COLOR' | 'FLOAT';
  values: [string | number, string | number];
}

type DtcgLeaf = { $type: string; $value: unknown };

/** Flatten a DTCG tree into "group/sub/name" leaves (the same names Figma's own import uses) */
function flattenDtcg(tree: object, prefix = ''): { name: string; token: DtcgLeaf }[] {
  return Object.entries(tree).flatMap(([key, node]) => {
    const name = prefix ? `${prefix}/${key}` : key;
    return '$type' in node ? [{ name, token: node as DtcgLeaf }] : flattenDtcg(node, name);
  });
}

/** Figma variables hold hex colors and plain numbers (px, seconds, unitless) */
function pluginValue({ $type, $value }: DtcgLeaf): string | number {
  if ($type === 'color') return ($value as { hex: string }).hex;
  if (typeof $value === 'number') return $value;
  return ($value as { value: number }).value;
}

function buildPluginCode(themes: Themes): string {
  const light = flattenDtcg(toDtcg(themes.light));
  const dark = flattenDtcg(toDtcg(themes.dark));
  const variables: PluginVariable[] = light.map(({ name, token }, i) => ({
    name,
    type: token.$type === 'color' ? 'COLOR' : 'FLOAT',
    values: [pluginValue(token), pluginValue(dark[i].token)],
  }));
  const tokens = { modes: ['Light', 'Dark'], variables };
  return `// Generated by Design System Builder on ${stamp()}\nvar TOKENS = ${JSON.stringify(tokens)};\n\n${pluginSource}`;
}

