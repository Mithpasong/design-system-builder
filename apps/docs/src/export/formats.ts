/* ---------- JSON: resolved values for an npm package ---------- */

function toResolved(theme: Theme) {
  const scale = getTypeScale(theme.typography);
  const px = (n: number) => `${n}px`;
  return {
    color: {
      ...Object.fromEntries(
        Object.entries({ ...theme.brand, ...theme.status }).flatMap(([k, v]) => [
          [k, v],
          [`${k}Foreground`, getForeground(v)],
        ]),
      ),
      ...theme.neutral,
      focusRing: theme.focusRing.color,
    },
    font: {
      size: Object.fromEntries(scale.map((s) => [s.name, px(s.fontSize)])),
      lineHeight: Object.fromEntries(scale.map((s) => [s.name, px(s.lineHeight)])),
      weight: { ...theme.typography.weights },
    },
    size: Object.fromEntries(
      Object.entries(theme.size).map(([k, v]) => [k, { height: px(v.height), paddingX: px(v.paddingX) }]),
    ),
    space: Object.fromEntries(getSpacingScale(theme.spacing).map((s) => [s.name, px(s.value)])),
    radius: { ...Object.fromEntries(Object.entries(theme.radius).map(([k, v]) => [k, px(v)])), full: '9999px' },
    borderWidth: Object.fromEntries(Object.entries(theme.border).map(([k, v]) => [k, px(v)])),
    shadow: Object.fromEntries(shadowLevels.map((l) => [l, getShadow(theme.shadow, l)])),
    motion: {
      duration: Object.fromEntries(Object.entries(theme.motion.duration).map(([k, v]) => [k, `${v}ms`])),
      easing: theme.motion.easing,
    },
    focusRing: { width: px(theme.focusRing.width), offset: px(theme.focusRing.offset) },
  };
}

export function buildJson(themes: Themes, meta: { name: string; version: string } = { name: PACKAGE_NAME, version: '1.0.0' }): string {
  return JSON.stringify(
    {
      name: meta.name,
      version: meta.version,
      generatedAt: new Date().toISOString(),
      modes: { light: toResolved(themes.light), dark: toResolved(themes.dark) },
      cssVariables: { light: getCssVariables(themes.light), dark: getCssVariables(themes.dark) },
    },
    null,
    2,
  );
}

/* ---------- HTML / CSS ---------- */

function cssBlock(selector: string, vars: Record<string, string>, extra: string, indent = ''): string {
  const lines = Object.entries(vars).map(([k, v]) => `${indent}  ${k}: ${v};`);
  return `${indent}${selector} {\n${indent}  ${extra}\n${lines.join('\n')}\n${indent}}`;
}

export function buildCss(themes: Themes): string {
  const light = getCssVariables(themes.light);
  const dark = getCssVariables(themes.dark);
  return `/* Design tokens - generated by Design System Builder on ${stamp()}
 *
 * Light is the default. Dark applies with <html data-theme="dark">,
 * or automatically when the OS prefers dark and data-theme isn't "light".
 */

${cssBlock(':root', light, 'color-scheme: light;')}

${cssBlock('[data-theme="dark"]', dark, 'color-scheme: dark;')}

@media (prefers-color-scheme: dark) {
${cssBlock(':root:not([data-theme="light"])', dark, 'color-scheme: dark;', '  ')}
}
`;
}

